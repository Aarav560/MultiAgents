const uint8_t *font_glyph(char ch) {
    int code = (unsigned char)ch;
    if (code < FONT_FIRST || code > FONT_LAST)
        code = '?';
    return font_table[code - FONT_FIRST];
}

int font_width(const char *s, int scale) {
    int best = 0, cur = 0;
    if (!s || scale < 1)
        return 0;
    for (; *s; s++) {
        if (*s == '\n') {
            cur = 0;
            continue;
        }
        cur += 8 * scale;
        if (cur > best)
            best = cur;
    }
    return best;
}

/* Blends color over the pixel at alpha 0..255, ignoring out-of-canvas coordinates. */
static void blend_px(canvas *c, int x, int y, uint32_t color, int alpha) {
    uint32_t *p, d;
    int r, g, b;
    if (x < 0 || y < 0 || x >= c->w || y >= c->h)
        return;
    p = &c->px[(size_t)y * (size_t)c->w + (size_t)x];
    if (alpha >= 255) {
        *p = color & 0xFFFFFFu;
        return;
    }
    d = *p;
    r = rgb_r(d) + (rgb_r(color) - rgb_r(d)) * alpha / 255;
    g = rgb_g(d) + (rgb_g(color) - rgb_g(d)) * alpha / 255;
    b = rgb_b(d) + (rgb_b(color) - rgb_b(d)) * alpha / 255;
    *p = rgb(r, g, b);
}

static void draw_glyph(canvas *c, int x, int y, const uint8_t *g, uint32_t color, int scale) {
    int row, col, i, j;
    int size = 8 * scale;
    if (x >= c->w || y >= c->h || x + size <= 0 || y + size <= 0)
        return;
    for (row = 0; row < 8; row++) {
        uint8_t bits = g[row];
        if (!bits)
            continue;
        for (col = 0; col < 8; col++) {
            if (!(bits & (1u << col)))
                continue;
            for (j = 0; j < scale; j++)
                for (i = 0; i < scale; i++)
                    blend_px(c, x + col * scale + i, y + row * scale + j, color, 255);
        }
    }
}

int font_draw(canvas *c, int x, int y, const char *s, uint32_t color, int scale) {
    int cx = x, cy = y;
    if (!s || scale < 1)
        return 0;
    if (c && c->px) {
        for (const char *p = s; *p; p++) {
            if (*p == '\n') {
                cx = x;
                cy += 8 * scale + 2;
                continue;
            }
            draw_glyph(c, cx, cy, font_glyph(*p), color, scale);
            cx += 8 * scale;
        }
    }
    return font_width(s, scale);
}
